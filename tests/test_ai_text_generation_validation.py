class TestRuleBasedSummary:
    """Tests for _generate_rule_based_summary()."""

    def test_summary_contains_case_id(self):
        case = _make_case(case_id="FALL-2026-S01")
        svc = _make_service()
        summary = svc._generate_rule_based_summary(case)
        assert "FALL-2026-S01" in summary

    def test_summary_contains_practice_name_and_id(self):
        case = _make_case(practice_name="Orthopädie Zentrum Nord", customer_id="KD-9988")
        svc = _make_service()
        summary = svc._generate_rule_based_summary(case)
        assert "Orthopädie Zentrum Nord" in summary
        assert "KD-9988" in summary

    def test_summary_contains_three_sections(self):
        case = _make_case()
        svc = _make_service()
        summary = svc._generate_rule_based_summary(case)
        assert "1. PROBLEM-ÜBERSICHT:" in summary
        assert "2. ZEITLEISTE & MASSNAHMEN:" in summary
        assert "3. NÄCHSTER SCHRITT:" in summary

    def test_summary_starts_with_emoji_prefix(self):
        case = _make_case()
        svc = _make_service()
        summary = svc._generate_rule_based_summary(case)
        assert summary.startswith("📌 FALL-ZUSAMMENFASSUNG")

    def test_summary_uses_classification_title(self):
        case = _make_case(title="eGK Kartenleser offline am Empfang")
        svc = _make_service()
        summary = svc._generate_rule_based_summary(case)
        assert "eGK Kartenleser offline am Empfang" in summary

    def test_summary_includes_form_data_description(self):
        case = _make_case(form_data={"unformatted_description": "Der Kartenterminal meldet Fehler KTR-402 seit 09:00 Uhr."})
        svc = _make_service()
        summary = svc._generate_rule_based_summary(case)
        assert "Kartenterminal" in summary
        assert "KTR-402" in summary

    def test_summary_with_timeline_entries(self):
        entries = [
            TimelineEntry(timestamp="2026-08-20T10:00:00", author="Max Mustermann", channel="PHONE_INBOUND", note="Rückruf vom Kunden"),
            TimelineEntry(timestamp="2026-08-21T14:30:00", author="Support", channel="INTERNAL_NOTE", note="Fernwartung durchgeführt"),
        ]
        case = _make_case(timeline=entries)
        svc = _make_service()
        summary = svc._generate_rule_based_summary(case)
        assert "Rückruf vom Kunden" in summary or "Fernwartung" in summary

    def test_summary_shows_no_timeline_message_when_empty(self):
        case = _make_case(timeline=[])
        svc = _make_service()
        summary = svc._generate_rule_based_summary(case)
        assert "Keine bisherigen Zeitleisten-Einträge" in summary

    def test_summary_shows_completed_status(self):
        case = _make_case(is_completed=True)
        svc = _make_service()
        summary = svc._generate_rule_based_summary(case)
        assert "✓ Fall abgeschlossen" in summary

    def test_summary_shows_followup_when_set(self):
        case = _make_case(followup_at="2026-09-01T10:00:00", followup_note="Rückruf wegen Update")
        svc = _make_service()
        summary = svc._generate_rule_based_summary(case)
        assert "Wiedervorlage" in summary or "Rückruf" in summary

    def test_summary_truncates_long_descriptions(self):
        long_desc = "A" * 500
        case = _make_case(form_data={"unformatted_description": long_desc})
        svc = _make_service()
        summary = svc._generate_rule_based_summary(case)
        # The rule-based engine truncates at 200 chars + "..."
        assert "..." in summary
        assert len(summary) < len(long_desc) + 500  # Generous upper bound


