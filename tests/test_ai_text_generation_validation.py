class TestSolutionSuggestions:
    """Tests for suggest_solutions() pattern matching."""

    def test_cobra_keyword_match(self):
        case = _make_case(form_data={"unformatted_description": "Cobra CRM Schnittstelle meldet Fehler beim Import"})
        svc = _make_service()
        solutions = svc.suggest_solutions(case)
        assert any("COBRA" in s["title"] for s in solutions)

    def test_erezept_keyword_match(self):
        case = _make_case(title="eRezept Signaturfehler")
        svc = _make_service()
        solutions = svc.suggest_solutions(case)
        assert any("eRezept" in s["title"] or "TI" in s["title"] for s in solutions)

    def test_labor_keyword_match(self):
        case = _make_case(title="LDT Laborbefund kommt nicht an")
        svc = _make_service()
        solutions = svc.suggest_solutions(case)
        assert any("Labor" in s["title"] or "LDT" in s["title"] for s in solutions)

    def test_default_solution_when_no_match(self):
        case = _make_case(title="Allgemeine Anfrage", form_data={"unformatted_description": "Allgemeines Problem"})
        svc = _make_service()
        solutions = svc.suggest_solutions(case)
        assert len(solutions) >= 1
        assert any("Standard" in s["title"] or "Logfile" in s["title"] for s in solutions)

    def test_wiki_article_matching(self):
        case = _make_case(title="Drucker offline seit heute morgen")
        svc = _make_service()
        wiki = [{"title": "Drucker Fehlerbehebung", "content": "Drucker-Spooler Dienst neu starten und Port prüfen."}]
        solutions = svc.suggest_solutions(case, wiki_articles=wiki)
        assert any("Wiki" in s["title"] for s in solutions)

    def test_solution_confidence_format(self):
        case = _make_case(title="cobra schnittstelle fehlt")
        svc = _make_service()
        solutions = svc.suggest_solutions(case)
        for sol in solutions:
            conf = sol.get("confidence", "")
            assert "%" in conf, f"Confidence should be percentage format, got: {conf}"

    def test_solution_has_required_fields(self):
        case = _make_case()
        svc = _make_service()
        solutions = svc.suggest_solutions(case)
        for sol in solutions:
            assert "title" in sol
            assert "snippet" in sol
            assert "confidence" in sol
            assert "source" in sol

    def test_multiple_keyword_matches(self):
        """A case mentioning both COBRA and eRezept should return solutions for both."""
        case = _make_case(
            title="cobra import",
            form_data={"unformatted_description": "Nach cobra Import funktioniert das eRezept nicht mehr"},
        )
        svc = _make_service()
        solutions = svc.suggest_solutions(case)
        titles = " ".join(s["title"] for s in solutions)
        assert "COBRA" in titles
        assert "eRezept" in titles or "TI" in titles


