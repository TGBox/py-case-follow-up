# --- Fixtures & Helpers ---

def _make_case(
    case_id: str = "FALL-2026-TV01",
    practice_name: str = "Praxis Dr. Meier",
    customer_id: str = "KD-1234",
    contact_person: str = "Frau Müller",
    title: str = "Drucker druckt nicht",
    board_column: str = "IN_PROGRESS",
    current_actor: str = "SUPPORT",
    form_data: dict | None = None,
    timeline: list[TimelineEntry] | None = None,
    is_vip: bool = False,
    followup_at: str = "",
    followup_note: str = "",
    is_completed: bool = False,
    custom_ai_rules: list[str] | None = None,
) -> Case:
    customer = CaseCustomer(
        customer_id=customer_id,
        practice_name=practice_name,
        contact_person=contact_person,
        is_vip=is_vip,
    )
    if custom_ai_rules is not None:
        customer.custom_ai_rules = custom_ai_rules  # type: ignore[attr-defined]
    return Case(
        case_id=case_id,
        customer=customer,
        classification=Classification(title=title, schema_id="DEFAULT_SCHEMA"),
        workflow_status=WorkflowStatus(
            board_column=board_column,
            current_actor=current_actor,
            followup_at=followup_at,
            followup_note=followup_note,
            is_completed=is_completed,
        ),
        form_data=form_data or {},
        timeline=timeline or [],
    )


def _make_service() -> AiService:
    """Creates an AiService that will always use the rule-based fallback (no real Ollama)."""
    return AiService(ollama_url="http://127.0.0.1:1", model_name="test-model")


