class TestSystemPromptBuilding:
    """Tests for build_system_prompt() hierarchical rule integration."""

    def test_prompt_includes_default_role(self):
        prompt = AiService.build_system_prompt()
        assert "IT-Support-Assistent" in prompt

    def test_prompt_includes_base_rules(self):
        rules = ["Immer im Sie-Stil antworten", "Keine internen Fachbegriffe"]
        prompt = AiService.build_system_prompt(base_rules=rules)
        assert "Immer im Sie-Stil antworten" in prompt
        assert "Keine internen Fachbegriffe" in prompt
        assert "GLOBALE BASIS-REGELN" in prompt

    def test_prompt_includes_practice_rules(self):
        practice_rules = ["Alle Antworten maximal 3 Sätze", "Immer auf Version 2.5 hinweisen"]
        prompt = AiService.build_system_prompt(practice_rules=practice_rules)
        assert "PRAXIS-SPEZIFISCHE REGELN" in prompt
        assert "Alle Antworten maximal 3 Sätze" in prompt

    def test_prompt_override_notice_with_practice_rules(self):
        prompt = AiService.build_system_prompt(
            base_rules=["Regel A"],
            practice_rules=["Regel B überschreibt A"],
        )
        assert "VORRANG" in prompt.upper() or "VORRANGIG" in prompt.upper()

    def test_prompt_without_any_rules(self):
        prompt = AiService.build_system_prompt(base_rules=[], practice_rules=[])
        assert "BASIS-REGELN" not in prompt
        assert "PRAXIS-SPEZIFISCHE" not in prompt

    def test_prompt_strips_whitespace_rules(self):
        rules = ["  Regel mit Leerzeichen  ", "   ", "Gültige Regel"]
        prompt = AiService.build_system_prompt(base_rules=rules)
        # Empty rules (whitespace-only) should be stripped and excluded
        assert "Regel mit Leerzeichen" in prompt
        assert "Gültige Regel" in prompt

    def test_prompt_with_custom_role(self):
        custom_role = "Du bist ein Abrechnungsexperte."
        prompt = AiService.build_system_prompt(default_role=custom_role)
        assert custom_role in prompt


