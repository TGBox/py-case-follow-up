class TestEdgeCases:
    """Edge cases for AI text generation."""

    def test_empty_case_generates_valid_summary(self):
        case = _make_case(
            title="",
            practice_name="",
            customer_id="",
            contact_person="",
            form_data={},
            timeline=[],
        )
        svc = _make_service()
        summary = svc._generate_rule_based_summary(case)
        assert isinstance(summary, str)
        assert len(summary) > 0
        assert "FALL-ZUSAMMENFASSUNG" in summary

    def test_unicode_characters_in_case(self):
        case = _make_case(
            title="Ärztliches Übergabe-Formular — Ñoño",
            practice_name="Praxis für Orthopädie & Rheumatologie",
            contact_person="Dr. med. Müller-Lüdenscheidt",
        )
        svc = _make_service()
        summary = svc._generate_rule_based_summary(case)
        assert "Ärztliches Übergabe-Formular" in summary
        assert "Orthopädie & Rheumatologie" in summary

        response = svc.generate_customer_response(case)
        assert "Müller-Lüdenscheidt" in response

    def test_very_long_timeline(self):
        """Many timeline entries should be handled gracefully (only last 3 shown in summary)."""
        entries = [
            TimelineEntry(
                timestamp=f"2026-08-{i:02d}T10:00:00",
                author="Support",
                channel="PHONE_INBOUND",
                note=f"Zeitleisten-Eintrag Nummer {i:02d}",
            )
            for i in range(1, 21)
        ]
        case = _make_case(timeline=entries)
        svc = _make_service()
        summary = svc._generate_rule_based_summary(case)
        # Should only show last 3 (entries 18, 19, 20)
        assert "Nummer 20" in summary
        assert "Nummer 18" in summary
        # Older ones should NOT be present (e.g. entry 5 or entry 15)
        assert "Nummer 15" not in summary
        assert "Nummer 05" not in summary

    def test_special_characters_in_form_data(self):
        case = _make_case(form_data={
            "unformatted_description": 'Fehler: "Ungültige Zeichen" <script>alert("XSS")</script> in der DB'
        })
        svc = _make_service()
        summary = svc._generate_rule_based_summary(case)
        assert isinstance(summary, str)
        assert "Ungültige Zeichen" in summary

    def test_ai_settings_round_trip(self):
        settings = AiSettings(
            ollama_url="http://192.168.1.100:11434",
            model_name="mistral:7b",
            enable_ai=False,
            base_rules=["Regel 1", "Regel 2"],
        )
        d = settings.to_dict()
        restored = AiSettings.from_dict(d)
        assert restored.ollama_url == "http://192.168.1.100:11434"
        assert restored.model_name == "mistral:7b"
        assert restored.enable_ai is False
        assert restored.base_rules == ["Regel 1", "Regel 2"]

    def test_summarize_case_uses_fallback_when_offline(self):
        """When Ollama is unreachable, summarize_case should use the rule-based fallback."""
        case = _make_case(title="Terminkalender-Ansicht eingefroren")
        svc = _make_service()  # points to unreachable URL
        summary = svc.summarize_case(case)
        assert "FALL-ZUSAMMENFASSUNG" in summary
        assert "Terminkalender-Ansicht eingefroren" in summary

    def test_generate_response_uses_fallback_when_offline(self):
        """When Ollama is unreachable, generate_customer_response should use the template fallback."""
        case = _make_case(contact_person="Herr Dr. Weber")
        svc = _make_service()
        response = svc.generate_customer_response(case, user_name="Support-Team Süd")
        assert "Herr Dr. Weber" in response
        assert "Support-Team Süd" in response
        assert "Mit freundlichen Grüßen" in response
